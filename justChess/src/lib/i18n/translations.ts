export type TranslationKey = keyof typeof translations.en;
export type NestedTranslationKey<T> = T extends object
  ? { [K in keyof T]: K extends string
      ? T[K] extends object
        ? `${K}.${NestedTranslationKey<T[K]>}`
        : K
      : never
  }[keyof T]
  : never;
